def norm(lang):
    return lang if lang in LANGS else DEFAULT


def t(key, lang=DEFAULT, **kwargs):
    text = T[key].get(norm(lang)) or T[key][DEFAULT]
    return text.format(**kwargs) if kwargs else text


def alert(code, lang=DEFAULT):
    return ALERTS[code][norm(lang)] if code in ALERTS else code


def ui_strings(lang):
    return {k[3:]: t(k, lang) for k in T if k.startswith("ui.")}
